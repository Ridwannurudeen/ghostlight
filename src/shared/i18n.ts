export function isPhraseId(id: string): id is PhraseId {
  return Object.prototype.hasOwnProperty.call(PHRASE_TEXTS.en, id)
}

export function phraseText(id: string, language: Language): string | null {
  return isPhraseId(id) ? PHRASE_TEXTS[language][id] : null
}

export function phraseById(id: string, language: Language): Phrase | null {
  const phrase = DECK.find((candidate) => candidate.id === id)
  if (!phrase || !isPhraseId(id)) return null
  return { ...phrase, text: PHRASE_TEXTS[language][id] }
}

export function localizePhrase(phrase: Phrase, language: Language): Phrase {
  return { ...phrase, text: phraseText(phrase.id, language) ?? phrase.text }
}

export function localizeDeck(language: Language): Phrase[] {
  return DECK.map((phrase) => localizePhrase(phrase, language))
}
